_REGISTRY_LOCK = threading.RLock()


# ---------------------------------------------------------------------------
# Public Helper Functions
# ---------------------------------------------------------------------------

def _specs() -> list[TableStorageSpec]:
    with _REGISTRY_LOCK:
        return list(CORE_STORAGE_REGISTRY)


def get_definition_tables() -> list[str]:
    """Return all universe definition table names."""
    return [spec.table_name for spec in _specs() if not spec.is_runtime]


def get_runtime_tables() -> list[str]:
    """Return the per-save SQL tables, ``Saves`` last (purge order: children first).

    External stores (vector memory, files) and per-database tables
    (``Mod_Schema_Versions``) are not save rows and are not listed.
    """
    tables = [
        spec.table_name for spec in _specs()
        if spec.is_runtime and spec.save_scoped and not spec.external
    ]
    ordered = [t for t in reversed(tables) if t != "Saves"]
    if "Saves" in tables:
        ordered.append("Saves")
    return ordered


def get_definition_copy_specs() -> list[tuple[str, tuple[str, ...]]]:
    """Return (table_name, columns) pairs for copying universe definitions into a save db."""
    return [
        (spec.table_name, spec.columns)
        for spec in _specs()
        if not spec.is_runtime and spec.columns is not None
    ]


def get_runtime_copy_specs() -> list[tuple[str, tuple[str, ...]]]:
    """Return (table_name, columns) pairs for copying the per-save runtime rows."""
    return [
        (spec.table_name, spec.columns)
        for spec in _specs()
        if spec.is_runtime and spec.save_scoped and not spec.external and spec.columns is not None
    ]


def _table_exists(conn: sqlite3.Connection, table: str) -> bool:
    return conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?;", (table,)
    ).fetchone() is not None


def execute_rewind(
    conn: sqlite3.Connection,
    save_id: str,
    target_turn_id: int,
    *,
    external: bool = True,
) -> dict[str, int]:
    """Execute unified rewind on all registered SQL tables, on the caller's transaction.

    ``external=False`` leaves the non-SQL stores alone: the engine path
    (:meth:`axiom.checkpoint.CheckpointManager.rewind`) commits the SQL first,
    then calls :func:`execute_external_rewind`. ``external=True`` (default, kept
    for direct callers) runs them at the end of this call.
    """
    from axiom.schema import (
        ensure_facts_table,
        ensure_fired_event_turn_column,
        ensure_inventory_snapshots_table,
        ensure_modifier_snapshots_table,
    )

    ensure_fired_event_turn_column(conn)
    ensure_facts_table(conn)
    ensure_modifier_snapshots_table(conn)
    ensure_inventory_snapshots_table(conn)

    deleted_count = 0
    specs = [s for s in _specs() if not s.external]

    # 1. EVENTS (Event_Log)
    for spec in specs:
        if spec.policy == StoragePolicy.EVENTS:
            cur = conn.execute(
                f"DELETE FROM {spec.table_name} WHERE save_id = ? AND {spec.step_column} > ?;",
                (save_id, target_turn_id),
            )
            deleted_count += cur.rowcount or 0

    # 2. STEP_KEYED tables (a table not created yet in an old db has nothing to rewind)
    for spec in specs:
        if spec.policy == StoragePolicy.STEP_KEYED and _table_exists(conn, spec.table_name):
            conn.execute(
                f"DELETE FROM {spec.table_name} WHERE save_id = ? AND {spec.step_column} > ?;",
                (save_id, target_turn_id),
            )

    # 3. CUSTOM handlers
    for spec in specs:
        if spec.policy == StoragePolicy.CUSTOM and spec.custom_rewind is not None:
            spec.custom_rewind(conn, save_id, target_turn_id)

    if external:
        execute_external_rewind(save_id, target_turn_id)

    return {"deleted_events": deleted_count, "rebuilt_to_turn": target_turn_id}


def execute_external_rewind(save_id: str, target_turn_id: int) -> list[str]:
    """Rewind the external (non-SQL) stores. Call it AFTER the SQL rewind is committed.

    A failing store does not stop the others; it is logged and its name returned
    (the SQL state is already committed and stays the source of truth).
    """
    failed: list[str] = []
    for spec in _specs():
        if spec.external and spec.custom_rewind is not None:
            try:
                spec.custom_rewind(None, save_id, target_turn_id)
            except Exception:
                logger.exception(
                    "External storage '%s' (mod %s) failed to rewind save %s to turn %d",
                    spec.table_name, spec.owner, save_id, target_turn_id,
                )
                failed.append(spec.table_name)
    return failed


def _fork_generic(
    conn: sqlite3.Connection,
    spec: TableStorageSpec,
    src_save_id: str,
    dst_save_id: str,
    at_turn: int,
) -> dict[Any, Any]:
    """Copy the rows ``step_column <= at_turn`` of a step-keyed table from its
    declared columns. Returns the {old_id: new_id} mapping (empty without id_column)."""
    if spec.columns is None or spec.step_column is None:
        raise ValueError(f"Step-keyed table '{spec.table_name}' needs columns and a step_column.")
    data_cols = [c for c in spec.columns if c not in ("save_id", spec.id_column)]
    select_cols = ([spec.id_column] if spec.id_column else []) + data_cols
    order = f" ORDER BY {spec.id_column}" if spec.id_autoincrement else ""
    rows = conn.execute(
        f"SELECT {', '.join(select_cols)} FROM {spec.table_name} "
        f"WHERE save_id = ? AND {spec.step_column} <= ?{order};",
        (src_save_id, at_turn),
    ).fetchall()

    id_map: dict[Any, Any] = {}
    insert_cols = ["save_id"] + data_cols
    if spec.id_column and not spec.id_autoincrement:
        insert_cols = [spec.id_column] + insert_cols
    sql = (
        f"INSERT INTO {spec.table_name} ({', '.join(insert_cols)}) "
        f"VALUES ({', '.join('?' * len(insert_cols))});"
    )
    for row in rows:
        values = list(row)
        old_id = values.pop(0) if spec.id_column else None
        params = [dst_save_id] + values
        if spec.id_column and not spec.id_autoincrement:
            new_id: Any = str(uuid.uuid4())
            params = [new_id] + params
            conn.execute(sql, params)
        else:
            new_id = conn.execute(sql, params).lastrowid
        if spec.id_column:
            id_map[old_id] = new_id
    return id_map


def execute_fork(
    conn: sqlite3.Connection,
    src_save_id: str,
    dst_save_id: str,
    at_turn: int,
    *,
    external: bool = True,
) -> dict[str, dict[Any, Any]]:
    """Copy all registered runtime tables from src_save_id up to at_turn into dst_save_id.

    Generic for EVENTS / STEP_KEYED tables (declared columns, ids regenerated);
    CUSTOM tables use their handler. Errors propagate: a fork never silently
    drops data. Returns the id mappings {table: {old_id: new_id}}.
    ``external=False``: the caller runs :func:`execute_external_fork` after its commit.
    """
    from axiom.schema import (
        ensure_facts_table,
        ensure_fired_event_turn_column,
        ensure_inventory_snapshots_table,
        ensure_modifier_snapshots_table,
    )
    ensure_fired_event_turn_column(conn)
    ensure_facts_table(conn)
    ensure_modifier_snapshots_table(conn)
    ensure_inventory_snapshots_table(conn)

    id_maps: dict[str, dict[Any, Any]] = {}
    for spec in _specs():
        if not spec.is_runtime or not spec.save_scoped or spec.external or spec.fork_with:
            continue
        if spec.custom_fork is not None:
            if spec.owner is None:
                spec.custom_fork(conn, src_save_id, dst_save_id, at_turn, id_maps=id_maps)
            else:
                spec.custom_fork(conn, src_save_id, dst_save_id, at_turn)
        elif spec.policy in (StoragePolicy.EVENTS, StoragePolicy.STEP_KEYED):
            if _table_exists(conn, spec.table_name):
                id_maps[spec.table_name] = _fork_generic(conn, spec, src_save_id, dst_save_id, at_turn)

    if external:
        execute_external_fork(src_save_id, dst_save_id, at_turn)
    return id_maps


def execute_external_fork(src_save_id: str, dst_save_id: str, at_turn: int) -> list[str]:
    """Fork the external (non-SQL) stores. Call it AFTER the SQL fork is committed."""
    failed: list[str] = []
    for spec in _specs():
        if spec.external and spec.custom_fork is not None:
            try:
                spec.custom_fork(None, src_save_id, dst_save_id, at_turn)
            except Exception:
                logger.exception(
                    "External storage '%s' (mod %s) failed to fork save %s at turn %d",
                    spec.table_name, spec.owner, src_save_id, at_turn,
                )
                failed.append(spec.table_name)
    return failed


def register_table_storage(spec: TableStorageSpec) -> TableStorageSpec | None:
    """Register or replace a table storage specification. Returns the replaced spec."""
    with _REGISTRY_LOCK:
        for i, s in enumerate(CORE_STORAGE_REGISTRY):
            if s.table_name == spec.table_name:
                CORE_STORAGE_REGISTRY[i] = spec
                return s
        CORE_STORAGE_REGISTRY.append(spec)
        return None


def register_custom_storage(
    table_name: str,
    rewind_callback: Callable[[sqlite3.Connection | None, str, int], None] | None = None,
    fork_callback: Callable[[sqlite3.Connection | None, str, str, int], None] | None = None,
    *,
    owner: str | None = None,
) -> TableStorageSpec:
    """Register an external (non-SQL) store: vector DB, generated files...

    Its callbacks run after the SQL rewind/fork is committed and receive
    ``conn=None``. Mods should go through ``ModContext.register_storage`` so the
    registration is removed when the mod is disabled (D11).
    """
    spec = TableStorageSpec(
        table_name=table_name,
        policy=StoragePolicy.CUSTOM,
        step_column=None,
        is_runtime=True,
        custom_rewind=rewind_callback,
        custom_fork=fork_callback,
        save_scoped=False,
        external=True,
        owner=owner,
    )
    register_table_storage(spec)
    return spec


def unregister_storage(spec: TableStorageSpec) -> bool:
    """Remove exactly this registration (a newer one with the same name is kept)."""
    with _REGISTRY_LOCK:
        for i, s in enumerate(CORE_STORAGE_REGISTRY):
            if s is spec:
                del CORE_STORAGE_REGISTRY[i]
                return True
    return False


# ---------------------------------------------------------------------------
# Mod schema migrations (per save database)
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ModMigrations:
    mod_id: str
    target_version: int
    migrations: dict[int, Callable[[sqlite3.Connection], None]]


_MOD_MIGRATIONS: dict[str, ModMigrations] = {}


def register_mod_migrations(
    mod_id: str,
    target_version: int,
    migrations: dict[int, Callable[[sqlite3.Connection], None]],
) -> ModMigrations:
    """Declare a mod's table migrations (version N -> N+1 callables).

    They are applied to every save database the engine opens or creates
    (:func:`apply_registered_mod_migrations`), tracked in ``Mod_Schema_Versions``.
    """
    entry = ModMigrations(mod_id, int(target_version), dict(migrations))
    with _REGISTRY_LOCK:
        _MOD_MIGRATIONS[mod_id] = entry
    return entry


def unregister_mod_migrations(entry: ModMigrations) -> None:
    with _REGISTRY_LOCK:
        if _MOD_MIGRATIONS.get(entry.mod_id) is entry:
            del _MOD_MIGRATIONS[entry.mod_id]


def get_registered_mod_migrations() -> list[ModMigrations]:
    with _REGISTRY_LOCK:
        return list(_MOD_MIGRATIONS.values())


def apply_registered_mod_migrations(db_path: str) -> list[str]:
    """Bring the mods' tables of ``db_path`` to their declared versions.

    A failing migration raises (its own transaction is rolled back): the save
    must not be played with a half-migrated mod schema. Returns the mod ids processed.
    """
    from axiom.schema import apply_mod_migrations

    done: list[str] = []
    for entry in get_registered_mod_migrations():
        apply_mod_migrations(str(db_path), entry.mod_id, entry.target_version, entry.migrations)
        done.append(entry.mod_id)
    return done
