"""axiom/storage_registry.py

Central persistence registry and storage policies for universe definitions and
save states in Axiom AI.

Replaces hardcoded table lists across checkpoint rewind, save forking,
packaging, and savestore copies with unified declarative policies (Phase 0c).

Policies:

- ``EVENTS`` / ``STEP_KEYED``: rows carry a step column. Rewind deletes the rows
  ``> N``; fork copies the rows ``<= N`` **generically** from the declared
  ``columns`` (``id_column`` regenerated: new AUTOINCREMENT value or new uuid).
  A new step-keyed table only needs to be declared, not coded.
- ``VERSIONED_KV``: definition tables and per-save rows that rewind/fork leave alone.
- ``DERIVED``: caches rebuilt from the journal (``State_Cache``): never copied or
  rewound by the registry; ``CheckpointManager.rewind`` / ``fork_save`` rebuild them.
- ``CUSTOM``: a handler is unavoidable. Each core handler says why (ids stored
  inside JSON payloads that must be remapped with ONE mapping, or snapshot-based
  state that cannot be filtered by a step column).

Stores outside the save database (vector memory, illustration files) are
registered by mods as *external* storages: they are rewound **after** the SQL
rewind is committed, never inside the transaction.
"""

from __future__ import annotations

import json
import sqlite3
import threading
import uuid
from dataclasses import dataclass
from enum import Enum
from typing import Any, Callable

from axiom.logger import logger


class StoragePolicy(Enum):
    EVENTS = "events"                     # Journal append-only réductible (Event_Log)
    STEP_KEYED = "step_keyed_table"       # Table SQL avec colonne step/turn explicite
    VERSIONED_KV = "versioned_kv"         # Clé-valeur avec borne de validité temporelle
    DERIVED = "derived"                   # Cache reconstruit depuis le journal (State_Cache)
    CUSTOM = "custom"                     # Gestionnaire externe (Vector DB, snapshots, etc.)


@dataclass(frozen=True)
class TableStorageSpec:
    table_name: str
    policy: StoragePolicy
    step_column: str | None = "turn_id"   # Colonne horodatée pour STEP_KEYED
    is_runtime: bool = True               # True = runtime/save, False = définition d'univers
    columns: tuple[str, ...] | None = None
    custom_rewind: Callable[..., Any] | None = None
    custom_fork: Callable[..., Any] | None = None
    # Identifier column regenerated by the generic fork (None = natural key kept).
    id_column: str | None = None
    id_autoincrement: bool = False        # True: INTEGER AUTOINCREMENT; False: new uuid4 text
    # The table carries a save_id column (per-save rows). False for per-database
    # tables (Mod_Schema_Versions) and for external stores.
    save_scoped: bool = True
    # Copied by the fork handler of another table (ids inside JSON payloads that
    # must share that handler's id mapping). The generic fork skips it.
    fork_with: str | None = None
    # Non-SQL store (vector DB, files): rewound/forked after the SQL commit; conn is None.
    external: bool = False
    owner: str | None = None              # Mod id that registered the spec (None = core)


# ---------------------------------------------------------------------------
# Custom Rollback & Fork Callbacks (core)
# ---------------------------------------------------------------------------
# Core fork handlers receive ``id_maps``: {table_name: {old_id: new_id}} filled
# by the tables forked before them (registry order), so ids that are stored in
# JSON (`sources`) can be rewritten.

def _remap_fact_sources(raw: Any, fact_map: dict[Any, Any]) -> str:
    """Rewrite an Observations ``sources`` list ([{fact_id, turn_id}]) with the forked fact ids."""
    try:
        sources = json.loads(raw) if isinstance(raw, str) else (raw or [])
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Invalid Observations.sources JSON: {raw!r}") from exc
    out = []
    for src in sources if isinstance(sources, list) else []:
        if not isinstance(src, dict):
            continue
        new = dict(src)
        fid = src.get("fact_id")
        try:
            fid = int(fid) if fid is not None else None
        except (TypeError, ValueError):
            fid = None
        # A fact at a turn after the fork point was not copied: the rollback below
        # drops that source anyway (its turn_id > N). Never keep a source id.
        new["fact_id"] = fact_map.get(fid) if fid is not None else None
        out.append(new)
    return json.dumps(out, ensure_ascii=False)


def _rewind_observations(conn: sqlite3.Connection, save_id: str, target_turn: int) -> None:
    from axiom.observations import rollback_observations
    rollback_observations(conn, save_id, target_turn)


def _fork_observations(
    conn: sqlite3.Connection, src_save_id: str, dst_save_id: str, target_turn: int,
    *, id_maps: dict[str, dict[Any, Any]],
) -> None:
    """Beliefs at the fork point = copy of the beliefs born <= N, then the same
    rollback as a rewind to N (sources > N dropped, proof_count recomputed,
    updated_turn_id clamped, stale flagged). Custom because ``sources`` holds
    fact ids (JSON) that must follow the forked Facts ids.
    """
    from axiom.observations import rollback_observations
    from axiom.schema import ensure_observations_table

    ensure_observations_table(conn)
    fact_map = id_maps.get("Facts", {})
    obs_map: dict[Any, Any] = {}
    rows = conn.execute(
        "SELECT observation_id, subject, statement, proof_count, sources, history, "
        "created_turn_id, updated_turn_id, stale "
        "FROM Observations WHERE save_id = ? AND created_turn_id <= ? ORDER BY observation_id;",
        (src_save_id, target_turn),
    ).fetchall()
    for r in rows:
        cur = conn.execute(
            "INSERT INTO Observations (save_id, subject, statement, proof_count, sources, "
            "history, created_turn_id, updated_turn_id, stale) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?);",
            (dst_save_id, r[1], r[2], r[3], _remap_fact_sources(r[4], fact_map), r[5], r[6], r[7], r[8]),
        )
        obs_map[int(r[0])] = cur.lastrowid
    id_maps["Observations"] = obs_map
    rollback_observations(conn, dst_save_id, target_turn)


def _rewind_mental_models(conn: sqlite3.Connection, save_id: str, target_turn: int) -> None:
    from axiom.mental_models import rollback_mental_models
    rollback_mental_models(conn, save_id, target_turn)


def _fork_mental_models(
    conn: sqlite3.Connection, src_save_id: str, dst_save_id: str, target_turn: int,
    *, id_maps: dict[str, dict[Any, Any]],
) -> None:
    """Same rule as the beliefs: copy the models born <= N, then rewind them to N.
    Custom because ``sources`` holds observation ids (JSON)."""
    from axiom.mental_models import rollback_mental_models
    from axiom.schema import ensure_mental_models_table

    ensure_mental_models_table(conn)
    obs_map = id_maps.get("Observations", {})
    rows = conn.execute(
        "SELECT model_id, subject, summary, sources, created_turn_id, updated_turn_id, stale "
        "FROM Mental_Models WHERE save_id = ? AND created_turn_id <= ? ORDER BY model_id;",
        (src_save_id, target_turn),
    ).fetchall()
    model_map: dict[Any, Any] = {}
    for r in rows:
        try:
            sources = json.loads(r[3]) if r[3] else []
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Invalid Mental_Models.sources JSON: {r[3]!r}") from exc
        remapped = []
        for s in sources if isinstance(sources, list) else []:
            try:
                old = int(s)
            except (TypeError, ValueError):
                continue
            if old in obs_map:
                remapped.append(obs_map[old])
        cur = conn.execute(
            "INSERT INTO Mental_Models (save_id, subject, summary, sources, created_turn_id, "
            "updated_turn_id, stale) VALUES (?, ?, ?, ?, ?, ?, ?);",
            (dst_save_id, r[1], r[2], json.dumps(remapped), r[4], r[5], r[6]),
        )
        model_map[int(r[0])] = cur.lastrowid
    id_maps["Mental_Models"] = model_map
    rollback_mental_models(conn, dst_save_id, target_turn)


